"""Generate portable exact-release metadata from pinned original input tables."""
from pathlib import Path
import argparse, hashlib, json, re
p = argparse.ArgumentParser()
p.add_argument('--original', type=Path, required=True)
p.add_argument('--check', action='store_true')
a = p.parse_args()
root = Path(__file__).resolve().parents[2]
source = (a.original / 'b4.c').read_text()
defs = (a.original / 'bsim4def.h').read_text()
ids = {m[1]: int(m[2]) for m in re.finditer(r'^#define\s+(BSIM4_\w+)\s+(\d+)\s*$', defs, re.M)}
parts = source.split('IFparm BSIM4mPTable[]')
rows = []
for role, text in zip(('instance', 'model'), parts):
    canonical = {}
    for m in re.finditer(r'\b(?:IOP|IP|IOPR)\s*\(\s*"([^"]+)"\s*,\s*(\w+)\s*,\s*(\w+)', text):
        name, symbol, kind = m.groups()
        if role == 'instance' and name == 'sc': symbol = 'BSIM4_SC'
        selector = ids[symbol]
        canonical.setdefault(selector, name)
        rows.append(dict(role=role, name=name, selector=selector, symbol=symbol,
                         kind={'IF_REAL':'real','IF_INTEGER':'integer','IF_FLAG':'flag','IF_STRING':'text','IF_REALVEC':'vector'}[kind],
                         canonicalName=canonical[selector]))
assert sum(x['role'] == 'model' for x in rows) == 746
assert sum(x['role'] == 'instance' for x in rows) == 33
manifest = dict(release='4.5.0', adaptation='sc-selector-v1',
                originals={n:hashlib.sha256((a.original/n).read_bytes()).hexdigest() for n in ('b4.c','bsim4def.h')}, parameters=rows)
swift = '''// Generated by tools/bsim45/generate_schema.py; original hashes are in schema.json.
// The SC selector is deliberately corrected; physical defaults remain kernel-owned.
enum BSIM45SchemaCatalog {
    struct Entry { let parameter: MOSSchemaCatalog.Parameter; let selector: Int32 }
'''
for role in ('instance','model'):
    swift += f'    static let {role} = catalog("""\n'
    for r in rows:
        if r['role'] != role: continue
        swift += f'    {r["name"]} {r["selector"]} {r["kind"]} {r["canonicalName"]}\n'
    swift += '    """)\n'
swift += '''    // Decode the pinned table once. A large dictionary literal would place all
    // temporary entries on the limited WASM stack before storage allocation.
    private static func catalog(_ records: String) -> [String: Entry] {
        var result: [String: Entry] = [:]
        for line in records.split(separator: "\\n") {
            let fields = line.split(separator: " ")
            precondition(fields.count == 4)
            guard let selector = Int32(fields[1]) else { preconditionFailure("Invalid generated selector") }
            let kind: MOSParameterKind
            switch fields[2] {
            case "real": kind = .real
            case "integer": kind = .integer
            case "flag": kind = .flag
            case "text": kind = .text
            case "vector": kind = .vector
            default: preconditionFailure("Invalid generated kind")
            }
            result[String(fields[0])] = Entry(parameter: .init(kind: kind, canonicalName: String(fields[3])), selector: selector)
        }
        return result
    }
}
'''
outputs = {root/'tools/bsim45/schema.json':json.dumps(manifest,indent=2)+'\n',
           root/'Sources/CoreSpiceMOSContracts/Schema/BSIM45SchemaCatalog.swift':swift}
for path, content in outputs.items():
    if a.check: assert path.read_text() == content, path
    else: path.write_text(content)
